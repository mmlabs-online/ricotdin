"""Pure DDL emitters for the v2 baseline (ARC-02).

The baseline generator reads the replayed v1 catalog and hands plain rows to these functions;
they return SQL text with Supabase references rewritten (``v1_rewrite``). No I/O here.
"""

import re
from dataclasses import dataclass

from app.db.v1_rewrite import map_role, rewrite_v1_sql

# Reserved keywords that cannot be bare column/table names (subset that can plausibly occur).
_RESERVED = {
    "all", "analyse", "analyze", "and", "any", "array", "as", "asc", "both", "case", "cast",
    "check", "collate", "column", "constraint", "create", "current_date", "current_role",
    "current_time", "current_timestamp", "current_user", "default", "deferrable", "desc",
    "distinct", "do", "else", "end", "except", "false", "fetch", "for", "foreign", "from",
    "grant", "group", "having", "in", "initially", "intersect", "into", "lateral", "leading",
    "limit", "localtime", "localtimestamp", "not", "null", "offset", "on", "only", "or",
    "order", "placing", "primary", "references", "returning", "select", "session_user", "some",
    "symmetric", "table", "then", "to", "trailing", "true", "union", "unique", "user", "using",
    "variadic", "when", "where", "window", "with",
}  # fmt: skip
_BARE = re.compile(r"^[a-z_][a-z0-9_]*$")


def quote_ident(name: str) -> str:
    if _BARE.match(name) and name not in _RESERVED:
        return name
    return '"' + name.replace('"', '""') + '"'


def quote_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _q(table: str) -> str:
    return f"public.{quote_ident(table)}"


def emit_enum(name: str, labels: list[str]) -> str:
    return f"CREATE TYPE {_q(name)} AS ENUM ({', '.join(quote_literal(x) for x in labels)});"


@dataclass(frozen=True)
class Column:
    name: str
    type: str
    not_null: bool
    default: str | None = None
    identity: str = ""  # '' | 'a' (ALWAYS) | 'd' (BY DEFAULT)
    generated: str | None = None  # stored generation expression


def _column_sql(c: Column) -> str:
    parts = [quote_ident(c.name), c.type]
    if c.not_null:
        parts.append("NOT NULL")
    if c.generated is not None:
        parts.append(f"GENERATED ALWAYS AS ({rewrite_v1_sql(c.generated)}) STORED")
    elif c.default is not None:
        parts.append(f"DEFAULT {rewrite_v1_sql(c.default)}")
    if c.identity == "a":
        parts.append("GENERATED ALWAYS AS IDENTITY")
    elif c.identity == "d":
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    return "  " + " ".join(parts)


def emit_table(name: str, columns: list[Column]) -> str:
    body = ",\n".join(_column_sql(c) for c in columns)
    return f"CREATE TABLE {_q(name)} (\n{body}\n);"


@dataclass(frozen=True)
class Policy:
    table: str
    name: str
    permissive: bool
    cmd: str  # ALL | SELECT | INSERT | UPDATE | DELETE
    roles: list[str]
    qual: str | None
    with_check: str | None


def _map_roles(roles: list[str]) -> list[str]:
    out: list[str] = []
    for r in roles:
        mapped = "PUBLIC" if r == "public" else map_role(r)
        if mapped is not None and mapped not in out:
            out.append(mapped)
    return out


def emit_policy(p: Policy) -> str | None:
    """CREATE POLICY for v2, or None when every v1 role of the policy has no v2 counterpart."""
    roles = _map_roles(p.roles)
    if not roles:
        return None
    sql = (
        f"CREATE POLICY {quote_ident(p.name)} ON {_q(p.table)} "
        f"AS {'PERMISSIVE' if p.permissive else 'RESTRICTIVE'} FOR {p.cmd} TO {', '.join(roles)}"
    )
    if p.qual is not None:
        sql += f" USING ({rewrite_v1_sql(p.qual)})"
    if p.with_check is not None:
        sql += f" WITH CHECK ({rewrite_v1_sql(p.with_check)})"
    return sql + ";"


def emit_table_grants(table: str, grants: list[tuple[str, str, str | None]]) -> list[str]:
    """GRANTs for one table from (v1 grantee, privilege, column-or-None) rows.

    Table-level privileges are merged per role; column-level ones get one statement per
    (role, privilege). Roles without a v2 counterpart are dropped.
    """
    table_level: dict[str, set[str]] = {}
    column_level: dict[tuple[str, str], set[str]] = {}
    for grantee, privilege, column in grants:
        role = map_role(grantee)
        if role is None:
            continue
        if column is None:
            table_level.setdefault(role, set()).add(privilege)
        else:
            column_level.setdefault((role, privilege), set()).add(column)
    out: list[str] = []
    for role in sorted(table_level.keys() | {r for r, _ in column_level}):
        if role in table_level:
            privs = ", ".join(sorted(table_level[role]))
            out.append(f"GRANT {privs} ON TABLE {_q(table)} TO {role};")
        for (r, privilege), cols in sorted(column_level.items()):
            if r == role:
                col_list = ", ".join(quote_ident(c) for c in sorted(cols))
                out.append(f"GRANT {privilege} ({col_list}) ON TABLE {_q(table)} TO {role};")
    return out


def emit_function_acl(signature: str, grantees: list[str] | None) -> list[str]:
    """EXECUTE privileges for a function.

    ``None`` = default ACL (PUBLIC may execute): nothing to emit.

    Otherwise the default is revoked and only the mapped grantees get EXECUTE (CLAUDE.md §6:
    "No GRANT does NOT mean not callable").
    """
    if grantees is None:
        return []
    out = [f"REVOKE ALL ON FUNCTION {signature} FROM PUBLIC;"]
    seen: set[str] = set()
    for g in grantees:
        role = map_role(g)
        if role is None or role in seen:
            continue
        seen.add(role)
        out.append(f"GRANT EXECUTE ON FUNCTION {signature} TO {role};")
    return out


def emit_seed(table: str, rows_json: str) -> str:
    """Insert rows (a JSON array of objects) into a table, keeping every column's type."""
    if "$seed$" in rows_json:
        raise ValueError("seed data contains the dollar-quote tag")
    # Generator output written to a reviewed .sql file; inputs come from the catalog, not users.
    head = f"INSERT INTO {_q(table)} SELECT * FROM jsonb_populate_recordset("  # noqa: S608
    return f"{head}NULL::{_q(table)}, $seed${rows_json}$seed$::jsonb);"
