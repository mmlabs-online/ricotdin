"""Assemble the v2 baseline SQL from a replayed v1 schema snapshot (ARC-02). Pure.

Order follows dependencies: functions come before tables because v1 SQL functions reference
tables and ``check_function_bodies`` is off; constraints are added after all tables exist
(foreign keys last); policies, grants and seed rows come once everything they touch exists.
"""

from app.db.ddl import (
    emit_enum,
    emit_function_acl,
    emit_policy,
    emit_seed,
    emit_table,
    emit_table_grants,
    quote_ident,
    quote_literal,
)
from app.db.introspect import Schema
from app.db.v1_rewrite import rewrite_v1_sql

_CONSTRAINT_ORDER = {"p": 0, "u": 1, "x": 2, "c": 3, "f": 4}


def _section(title: str, lines: list[str]) -> str:
    bar = "-- " + "-" * 93
    return "\n".join([bar, f"-- {title}", bar, *lines, ""])


def _qualified(name: str) -> str:
    return f"public.{quote_ident(name)}"


def render_baseline(
    schema: Schema,
    *,
    prelude: str,
    epilogue: str,
    overrides: dict[str, str],
    skip_functions: set[str],
) -> str:
    s = schema
    t = _qualified

    functions: list[str] = []
    acls: list[str] = []
    for f in s.functions:
        if f.name in skip_functions:
            continue
        body = overrides[f.name] if f.name in overrides else rewrite_v1_sql(f.definition)
        functions.append(body.rstrip().rstrip(";") + ";\n")
        acls.extend(emit_function_acl(f.signature, f.grantees))

    constraints = sorted(s.constraints, key=lambda c: (_CONSTRAINT_ORDER[c[2]], c[0], c[1]))
    rls_tables = [name for name, (enabled, _) in sorted(s.rls.items()) if enabled]

    comments = []
    for table, column, text in s.comments:
        target = (
            f"TABLE {t(table)}" if column is None else f"COLUMN {t(table)}.{quote_ident(column)}"
        )
        comments.append(f"COMMENT ON {target} IS {quote_literal(text)};")

    policies = [sql for p in s.policies if (sql := emit_policy(p)) is not None]
    policies += [
        f"CREATE POLICY service_all ON {t(name)} AS PERMISSIVE FOR ALL "
        "TO ricotdin_service USING (true) WITH CHECK (true);"
        for name in rls_tables
    ]

    grants = [
        g
        for table in sorted(s.table_grants)
        for g in emit_table_grants(table, s.table_grants[table])
    ]

    parts = [
        "-- ARC-02 v2 baseline. GENERATED by app/api/scripts/gen_baseline.py from\n"
        "-- legacy/schema.sql + legacy/migrations 001–038 (replayed with a Supabase shim)\n"
        "-- plus migrations/src/*.sql.\n"
        "-- Do not edit by hand: change the sources and regenerate.\n",
        "SET check_function_bodies = false;\n",
        _section(
            "Extensions",
            [
                f"CREATE EXTENSION IF NOT EXISTS {quote_ident(e)} WITH SCHEMA public;"
                for e in s.extensions
            ],
        ),
        prelude.rstrip() + "\n",
        _section("Enums (v1)", [emit_enum(n, labels) for n, labels in sorted(s.enums.items())]),
        _section("Functions (v1, rewritten)", functions),
        _section(
            "Tables (v1)", [emit_table(n, cols) + "\n" for n, cols in sorted(s.tables.items())]
        ),
        _section(
            "Constraints (v1)",
            [
                f"ALTER TABLE {t(c[0])} ADD CONSTRAINT {quote_ident(c[1])} {rewrite_v1_sql(c[3])};"
                for c in constraints
            ],
        ),
        _section("Indexes (v1)", [rewrite_v1_sql(i[2]) + ";" for i in s.indexes]),
        _section("Comments (v1)", comments),
        _section("Triggers (v1)", [rewrite_v1_sql(tr[2]) + ";" for tr in s.triggers]),
        _section(
            "Row level security (v1)",
            [f"ALTER TABLE {t(n)} ENABLE ROW LEVEL SECURITY;" for n in rls_tables]
            + [
                f"ALTER TABLE {t(n)} FORCE ROW LEVEL SECURITY;"
                for n, (_, forced) in sorted(s.rls.items())
                if forced
            ],
        ),
        _section("Policies (v1, rewritten) + service_all", policies),
        _section("Grants (v1 roles mapped to ricotdin_app / ricotdin_service)", grants + acls),
        _section(
            "Seed rows (inserted by v1 migrations)",
            [emit_seed(n, rows) for n, rows in sorted(s.seeds.items()) if rows != "[]"],
        ),
        epilogue.rstrip() + "\n",
    ]
    return "\n".join(parts)
